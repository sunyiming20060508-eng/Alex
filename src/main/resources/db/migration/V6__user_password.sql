-- 登录方式扩展：给 user 表加密码列（支持"手机号 + 密码"登录与显式注册）。
-- 执行方式：由 Flyway 按版本号自动执行，不要再手工 source（存量库 baseline-version=16 已把 V1–V16 记成基线，只补 V17 以后）。
-- 不是幂等脚本，手工重复执行会报列已存在。
--
-- 为什么这一列可以为 NULL：项目原本只有验证码登录（黑马点评那套），存量账号从来没有密码。
-- 设成 NOT NULL 就得给老账号造一批默认密码，那既是安全隐患也是假数据。
-- NULL 的语义就是"这个账号没设置过密码，只能验证码登录"，密码登录时按未设置处理。
--
-- 存的是 BCrypt 哈希（$2a$10$… 共 60 字符），不是明文也不是 MD5/SHA：
-- BCrypt 自带随机盐、可调工作因子，同一密码两次哈希结果不同，撞库和彩虹表都不成立。
-- 100 是留给以后把工作因子从 10 提到 12 时长度还能容纳。

ALTER TABLE user
    ADD COLUMN password VARCHAR(100) DEFAULT NULL COMMENT 'BCrypt 哈希；NULL 表示未设置密码，只能验证码登录' AFTER gender;
