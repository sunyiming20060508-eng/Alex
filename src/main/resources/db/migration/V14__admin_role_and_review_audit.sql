-- 三处刻意的取舍，面试要能自己讲：
-- 1. **管理员就是 user.role=1，不另建 employee 表**。苍穹外卖有独立的 employee 和角色表，是因为它面向
--    门店员工、还要管店铺归属；本项目一期只有"平台侧少数处置者"这一种身份，多一张表就多一套要和 user
--    对齐的登录体系。代价是将来真要细分角色（内容审核 / 客服 / 运营）时得再迁一次，那时再把 role 换成
--    role_id 外键。
-- 2. **评价是"先发后审"**：status 默认 1（已通过、直接展示），管理员只做"驳回"和"恢复通过"两个动作。
--    反过来做先审后发，用户提交后半天看不见自己的评价，而本项目没有任何审核时效承诺。
--    驳回的效果是**从展示里消失、并且不再拉低展示分**，不是删行——用户写过的东西必须还能追溯。
-- 3. **不给 review.status 留"待审核"这一档**。既然默认就是已通过，第三态没有任何写入方，
--    留着只会让每个查询都要想一遍"这个值算不算数"。
--
-- 两列都带默认值，所以执行完**已有数据的行为不变**：所有历史用户是普通用户（下一步单独把 id=1 提成管理员），
-- 所有历史评价是"已通过"，商家展示分不会因为加了一列而突变。

ALTER TABLE user
    ADD COLUMN role TINYINT NOT NULL DEFAULT 0 COMMENT '0 普通用户 1 管理员' AFTER gender;

ALTER TABLE review
    ADD COLUMN status TINYINT NOT NULL DEFAULT 1 COMMENT '1 已通过（展示且计入展示分） 2 已驳回（不展示且不计入展示分）' AFTER images,
    ADD KEY idx_review_status (status, id);

