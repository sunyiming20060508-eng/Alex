-- 给第一个账号开管理员。
--
-- **为什么不放在 V14 里**：V14 是 schema 迁移（加 `user.role` 这一列、加 `review.status`），
-- 而"谁是管理员"是**授权数据**，两件事混在一个版本化脚本里有两个后果：
-- ① 换一套环境（新库、别人的库、CI）时，脚本会把他这个具体账号又提成管理员——
--    生产上这是权限事故，不是便利；
-- ② 授权变更没有审计入口：想撤掉一个管理员只能改历史迁移，而历史迁移是不能改的。
--
-- 所以这里是一份**运维动作**，需要谁管理员时由人显式执行一次，并且随时可以对账：
--   select id, phone, role from `user` where role = 1;
-- 撤回到"没有任何账号能进管理端"（上公网前的默认状态）：
--   update `user` set role = 0 where id = 1;
--
-- 注意：身份是登录时写进 Redis 会话的，改完库要**重新登录**才生效（详见 API_CONTRACT 的管理端一节）。

update life_service.`user` set role = 1 where id = 1;
